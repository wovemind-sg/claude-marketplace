#!/usr/bin/env python
"""Emit an idempotent goose SQL baseline migration from SQLModel metadata.

Run inside the target FastAPI project's venv (needs sqlalchemy; sqlmodel optional):

    cd <repo> && uv run python <path>/baseline_ddl.py --models app.db.models \
        --exclude-schema auth > migrations/00001_baseline.sql

Importing the models module imports the project's `app/__init__.py`, which asserts
required env vars — a `.env` must exist in the cwd, or point DOT_ENV_PATH at one.
"""

import argparse
import importlib
import os
import sys

import sqlalchemy as sa
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable


def _compile(ddl_cls, obj, dialect):
    """DDL text with IF NOT EXISTS; falls back to string patching on SQLAlchemy < 1.4."""
    try:
        text = str(ddl_cls(obj, if_not_exists=True).compile(dialect=dialect))
    except TypeError:
        text = str(ddl_cls(obj).compile(dialect=dialect))
        for kw in ("CREATE TABLE ", "CREATE UNIQUE INDEX ", "CREATE INDEX "):
            if text.lstrip().startswith(kw):
                text = text.replace(kw, kw[:-1] + " IF NOT EXISTS ", 1)
                break
    text = "\n".join(line.rstrip() for line in text.strip().splitlines())
    return text if text.endswith(";") else text + ";"


def _enum_ddl(col_type):
    name = col_type.name
    if getattr(col_type, "schema", None):
        name = f"{col_type.schema}.{name}"
    values = ", ".join("'" + v.replace("'", "''") + "'" for v in col_type.enums)
    return (
        "-- +goose StatementBegin\n"
        "DO $$ BEGIN\n"
        f"    CREATE TYPE {name} AS ENUM ({values});\n"
        "EXCEPTION WHEN duplicate_object THEN NULL;\n"
        "END $$;\n"
        "-- +goose StatementEnd"
    )


def _default_label(col):
    arg = getattr(col.default, "arg", None)
    if callable(arg):
        return getattr(arg, "__name__", repr(arg))
    return repr(arg)


def load_metadata(modules):
    sys.path.insert(0, os.getcwd())
    try:
        from sqlmodel import SQLModel

        metadata = SQLModel.metadata
    except ImportError:
        metadata = None
    for mod_name in modules:
        mod = importlib.import_module(mod_name)
        if metadata is None:
            for val in vars(mod).values():
                if isinstance(val, sa.MetaData):
                    metadata = val
                    break
    if metadata is None:
        sys.exit("error: no SQLModel.metadata and no sqlalchemy.MetaData found on the models module")
    return metadata


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--models", action="append", required=True, metavar="MODULE", help="e.g. app.db.models (repeatable)")
    ap.add_argument("--exclude-schema", action="append", default=[], metavar="NAME", help="skip tables in this schema (repeatable)")
    ap.add_argument("--dialect", default="postgresql", choices=["postgresql"])
    args = ap.parse_args()

    dialect = postgresql.dialect()
    metadata = load_metadata(args.models)
    tables = [t for t in metadata.sorted_tables if t.schema not in args.exclude_schema]
    if not tables:
        sys.exit(f"error: no tables found in {', '.join(args.models)} after excluding schemas {args.exclude_schema} — wrong module path?")

    out = [
        "-- +goose Up",
        "-- Baseline generated by fastapi-go-migration from SQLModel metadata.",
        "-- Idempotent: safe on a fresh DB and a no-op on a DB already migrated by Alembic.",
        "",
    ]
    seen_enums = set()
    py_defaults = []
    for table in tables:
        for col in table.columns:
            if isinstance(col.type, sa.Enum) and col.type.name and col.type.name not in seen_enums:
                seen_enums.add(col.type.name)
                out += [_enum_ddl(col.type), ""]
            if col.default is not None and col.server_default is None:
                py_defaults.append(f"{table.fullname}.{col.name} ({_default_label(col)})")
        out += [_compile(CreateTable, table, dialect), ""]
        for idx in sorted(table.indexes, key=lambda i: i.name or ""):
            out += [_compile(CreateIndex, idx, dialect)]
        if table.indexes:
            out.append("")

    if py_defaults:
        out += ["-- NOTE: columns with Python-side defaults (Go INSERT must supply): " + ", ".join(py_defaults), ""]

    out += [
        "-- +goose Down",
        "-- Intentionally a no-op: this baseline mirrors tables that already exist in production.",
        "-- Dropping them on `migrate down` would destroy data.",
    ]
    print("\n".join(out))


if __name__ == "__main__":
    main()
